# USO DE VARIABLES
# Las variables son contenedores que almacenan datos en la memoria del computador.
# En Python, no es necesario declarar el tipo de dato de una variable, ya que es dinámicamente tipada.
# Puedes asignar cualquier tipo de dato a una variable y cambiarlo en cualquier momento.
# Las variables deben comenzar con una letra o un guion bajo (_), y pueden contener letras, números y guiones bajos.
# No pueden contener espacios ni caracteres especiales.
# Las variables son sensibles a mayúsculas y minúsculas (case-sensitive).
# Es una buena práctica usar nombres descriptivos para las variables, utilizando minúsculas y guiones bajos para separar palabras (snake_case).
# Ejemplos:
nombre = input("¿Como te llamas?")
print("hola " + nombre)
